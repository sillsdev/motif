using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using SIL.LCModel.Core.KernelInterfaces;
using SIL.LCModel.Infrastructure;

namespace SIL.Motif.RecordStore.Lcm;

/// <summary>Builds, checks and portably identifies the metadata behind the static built-in layout table.</summary>
public static class LcmLayoutTable
{
    /// <summary>One line per class and per non-virtual built-in field; custom fields are project data, not table data.</summary>
    public static IReadOnlyList<string> Describe(IFwMetaDataCacheManaged metadata)
    {
        var lines = new List<string>();
        foreach (var c in metadata.GetClassIds().Order())
            lines.Add(string.Join(' ', "class", c, metadata.GetClassName(c), metadata.GetAbstract(c), c == 0 ? "-" : metadata.GetBaseClsId(c)));
        foreach (var f in BuiltInFields(metadata))
            lines.Add(string.Join(' ', "field", f, metadata.GetOwnClsName(f), metadata.GetFieldName(f), metadata.GetFieldType(f), metadata.GetDstClsId(f)));
        return lines;
    }

    public static string Digest(IEnumerable<string> description) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(string.Join('\n', description))));

    /// <summary>Throws when built-in metadata differs from the metadata the table was generated from.</summary>
    public static void Require(IReadOnlyList<string> description)
    {
        if (Digest(description) != BuiltInLayouts.MetadataDigest)
            throw new InvalidDataException("LCM built-in metadata differs from the pinned layout table; regenerate the table.");
    }

    public static void Require(IFwMetaDataCacheManaged metadata) => Require(Describe(metadata));

    /// <summary>
    /// Identity of a custom field that survives a different numeric field id: owner class, name, type and destination.
    /// Labels, help and writing-system selectors are editable settings and do not change who the field is.
    /// </summary>
    public static string CustomIdentity(string owner, string name, int type, int destination) =>
        Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(string.Join('\n', "motif-custom-field/1", owner, name,
            type.ToString(CultureInfo.InvariantCulture), destination.ToString(CultureInfo.InvariantCulture)))));

    /// <summary>The source text of BuiltInLayouts.g.cs for this metadata.</summary>
    public static string Generate(IFwMetaDataCacheManaged metadata)
    {
        var description = Describe(metadata);
        var digest = Digest(description);
        var pairs = BuiltInFields(metadata).Select(f => $"{f}:{metadata.GetFieldType(f)} ").ToArray();
        var text = new StringBuilder();
        text.Append("// Generated by LcmLayoutTable.Generate from pinned LCM metadata; do not edit.\n");
        text.Append("namespace SIL.Motif.RecordStore;\n\ninternal static partial class BuiltInLayouts\n{\n");
        text.Append(CultureInfo.InvariantCulture, $"    public const string Version = \"lcm-builtin/{digest[..16]}\";\n");
        text.Append(CultureInfo.InvariantCulture, $"    public const string MetadataDigest = \"{digest}\";\n\n    private const string Fields =\n");
        var line = new StringBuilder();
        var lines = new List<string>();
        foreach (var pair in pairs)
        {
            if (line.Length + pair.Length > 100) { lines.Add(line.ToString()); line.Clear(); }
            line.Append(pair);
        }
        if (line.Length > 0) lines.Add(line.ToString());
        text.Append(string.Join(" +\n", lines.Select(l => $"        \"{l}\"")));
        text.Append(";\n}\n");
        return text.ToString();
    }

    private static IEnumerable<int> BuiltInFields(IFwMetaDataCacheManaged metadata) =>
        metadata.GetFieldIds().Where(f => !metadata.get_IsVirtual(f) && !metadata.IsCustom(f)).Order();
}
