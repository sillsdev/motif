#!/usr/bin/env python3
"""Regenerate the Extended_Pictographic table from Unicode 17.0.0."""

import hashlib
from pathlib import Path
from urllib.request import urlopen

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/emoji/emoji-data.txt"
SHA256 = "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b"
OUTPUT = Path(__file__).resolve().parents[1] / "src/SIL.TextEditing.Markdown/ExtendedPictographic.cs"


def generate():
    with urlopen(URL, timeout=60) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Unicode emoji data checksum mismatch")
    ranges = []
    for line in data.decode("utf-8").splitlines():
        fields = line.split("#", 1)[0].strip().split(";")
        if len(fields) != 2 or fields[1].strip() != "Extended_Pictographic":
            continue
        bounds = fields[0].strip().split("..")
        start, end = int(bounds[0], 16), int(bounds[-1], 16)
        if ranges and start == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], end)
        else:
            ranges.append((start, end))
    if not ranges or ranges != sorted(ranges):
        raise ValueError("Expected sorted Extended_Pictographic ranges")
    rows = "\n".join(f"            0x{start:X}, 0x{end:X}," for start, end in ranges)
    source = f'''namespace SIL.TextEditing.Markdown
{{
    // Generated by tools/generate-extended-pictographic.py; Unicode {VERSION} Extended_Pictographic.
    // https://www.unicode.org/Public/{VERSION}/ucd/emoji/emoji-data.txt
    internal static class ExtendedPictographic
    {{
        static readonly int[] Ranges =
        {{
{rows}
        }};

        internal static bool Contains(int codePoint)
        {{
            int low = 0, high = Ranges.Length / 2 - 1;
            while (low <= high)
            {{
                int middle = low + (high - low) / 2;
                if (codePoint < Ranges[2 * middle]) high = middle - 1;
                else if (codePoint > Ranges[2 * middle + 1]) low = middle + 1;
                else return true;
            }}
            return false;
        }}
    }}
}}
'''
    OUTPUT.write_text(source, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    generate()
