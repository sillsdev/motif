    public static IReadOnlyList<InteractiveControlFamily> ClassifyMarkup(string markupType) =>
        MarkupFamilies.TryGetValue(markupType, out var family) ? [family] : [];

    public static int CountDeclarations(string markup, string markupType) =>
        MarkupElement.Matches(markup)
            .Count(match => string.Equals(match.Groups["name"].Value, markupType, StringComparison.Ordinal));
